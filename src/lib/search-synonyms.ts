/**
 * 사이트 검색 동의어 — 사람들이 치는 말과 쿠팡 상품명에 쓰이는 말이 다를 때.
 * 예) "계란"을 치면 상품명이 '신선한 대란', '특란 30구'인 것도 찾음.
 * 같은 줄에 있는 단어끼리 서로 같은 뜻으로 봅니다. 필요할 때 줄을 추가하세요.
 */
const groups: string[][] = [
  ['계란', '달걀', '대란', '특란', '왕란', '구운란', '훈제란'],
  ['휴지', '화장지', '두루마리'],
  ['생수', '먹는샘물'],
  ['키친타올', '키친타월', '키친 타올'],
  ['물티슈', '물 티슈'],
  ['기저귀', '팬티형', '밴드형'],
  ['노트북', '랩탑'],
  ['이어폰', '버즈', '에어팟'],
  ['선크림', '선블록', '썬크림', '선스크린'],
  ['세제', '세탁세제', '액체세제'],
  ['섬유유연제', '유연제'],
  ['햇반', '즉석밥'],
  ['라면', '컵라면', '봉지라면'],
  ['우유', '멸균우유'],
  ['패딩', '다운', '푸퍼'],
  ['운동화', '스니커즈'],
  ['영양제', '비타민', '보충제'],
  ['고양이 모래', '벤토나이트', '두부모래'],
  ['사료', '건식사료'],
];

/** 검색어와 같은 뜻의 단어들 (검색어 자신 포함, 없으면 검색어만) */
export function expandQuery(q: string): string[] {
  const n = q.trim().toLowerCase();
  const hit = groups.find((g) => g.some((w) => w.toLowerCase() === n));
  return hit ? [q.trim(), ...hit.filter((w) => w.toLowerCase() !== n)] : [q.trim()];
}
